import {readFile,readdir} from 'node:fs/promises';
import {join} from 'node:path';
import {createPublicKey} from 'node:crypto';
import {encryptPairing} from '../.github/actions/pilot-device/supervise-restricted.mjs';
const root=process.argv[2];
if(!root||!process.env.PILOT_RSA_MODULUS)throw Error('Diagnostic scope/key missing');
const names=(await readdir(join(root,'responses'))).filter(n=>/^\.operator-[0-9a-f-]{36}\.log$/.test(n));
const logs=[];
for(const name of names.slice(-2))logs.push({name,tail:(await readFile(join(root,'responses',name),'utf8')).slice(-16384)});
const key=createPublicKey({format:'jwk',key:{kty:'RSA',n:Buffer.from(process.env.PILOT_RSA_MODULUS,'base64').toString('base64url'),e:'AQAB'}});
process.stdout.write(encryptPairing(JSON.stringify({runId:process.env.GITHUB_RUN_ID,kind:'native-operator-diagnostics',logs}),key));
